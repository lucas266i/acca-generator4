create table if not exists public.match_lineups (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  team_id bigint references public.teams(id) on delete set null,
  player_id bigint references public.players(id) on delete set null,
  player_name text not null,
  position text,
  lineup_status text,
  jersey_number text,
  formation_position text,
  captain boolean default false,
  substitute boolean default false,
  source text not null default 'TheSportsDB',
  raw_data jsonb,
  updated_at timestamptz not null default now(),
  unique(match_id, player_name, team_id)
);

create index if not exists idx_match_lineups_match on public.match_lineups(match_id);
create index if not exists idx_match_lineups_team on public.match_lineups(team_id);
create index if not exists idx_match_lineups_player on public.match_lineups(player_id);

create table if not exists public.team_form_snapshots (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  team_id bigint not null references public.teams(id) on delete cascade,
  venue text not null check (venue in ('overall','home','away')),
  sample_size integer not null default 0,
  goals_for_avg numeric,
  goals_against_avg numeric,
  wins_rate numeric,
  draws_rate numeric,
  losses_rate numeric,
  corners_avg numeric,
  shots_avg numeric,
  shots_on_target_avg numeric,
  cards_avg numeric,
  source text not null default 'internal',
  generated_at timestamptz not null default now(),
  unique(match_id, team_id, venue)
);

create index if not exists idx_team_form_match on public.team_form_snapshots(match_id);
create index if not exists idx_team_form_team on public.team_form_snapshots(team_id);

comment on table public.match_lineups is 'TheSportsDB lineup observations for historical and upcoming matches. Empty upcoming lineups are valid until the provider publishes them.';
comment on table public.team_form_snapshots is 'Cached last-5 overall/home/away form features used by the prediction engine.';
